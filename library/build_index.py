#!/usr/bin/env python3
"""Rebuild library/INDEX.md from every SKILL.md under library/collections/.

Usage (from the repo root):  python3 library/build_index.py

Each line of the index is one skill:
    name | collection | path | description
One skill per line keeps the index greppable without reading it whole.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
COLLECTIONS = ROOT / "collections"
INDEX = ROOT / "INDEX.md"


def parse_frontmatter(text: str) -> dict:
    m = re.match(r"^---\s*\n(.*?)\n---", text, re.S)
    if not m:
        return {}
    fields, key = {}, None
    for line in m.group(1).splitlines():
        km = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if km:
            key = km.group(1)
            fields[key] = km.group(2).strip()
        elif key and line.startswith((" ", "\t")):
            fields[key] += " " + line.strip()
    for k, v in fields.items():
        v = v.strip()
        if v[:1] in "|>":
            v = v[1:].strip()
        fields[k] = v.strip("'\"")
    return fields


def main() -> int:
    rows = []
    for skill_md in sorted(COLLECTIONS.glob("*/**/SKILL.md")):
        rel = skill_md.relative_to(ROOT.parent)
        collection = skill_md.relative_to(COLLECTIONS).parts[0]
        fm = parse_frontmatter(skill_md.read_text(encoding="utf-8", errors="ignore"))
        name = fm.get("name") or skill_md.parent.name
        desc = re.sub(r"\s+", " ", fm.get("description", "")).replace("|", "/")
        rows.append(f"{name} | {collection} | {rel} | {desc}")

    header = (
        "# Skill library index\n\n"
        "Generated by library/build_index.py — do not edit by hand.\n"
        f"Skills: {len(rows)}\n\n"
        "Format: name | collection | path | description\n\n"
    )
    INDEX.write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"Indexed {len(rows)} skills -> {INDEX.relative_to(ROOT.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
